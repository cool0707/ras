pub fn find(code: &str) -> Option<&'static Entry> {
    let code = code.trim().to_uppercase();
    ENTRIES.iter().find(|e| e.code == code)
}

pub fn text(entry: &Entry) -> String {
    let kind = if entry.code.starts_with('W') {
        "警告"
    } else {
        "エラー"
    };
    let mut out = format!(
        "{} — {}（{kind}）\n\n{}\n",
        entry.code, entry.title, entry.body
    );
    if !entry.example.is_empty() {
        out.push_str("\n例:\n");
        for line in entry.example.lines() {
            out.push_str(&format!("    {line}\n"));
        }
    }
    out
}

/// `ras explain` without a code: the codes and what they are about.
pub fn list() -> String {
    ENTRIES
        .iter()
        .map(|e| format!("{}  {}\n", e.code, e.title))
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The codes written in the sources of the compiler and the CLI.
    fn codes_in(dir: &std::path::Path, out: &mut std::collections::BTreeSet<String>) {
        for entry in std::fs::read_dir(dir).unwrap().flatten() {
            let path = entry.path();
            if path.is_dir() {
                codes_in(&path, out);
            } else if path.extension().is_some_and(|e| e == "rs")
                && path.file_name().is_some_and(|n| n != "explain.rs")
            {
                let text = std::fs::read_to_string(&path).unwrap();
                let bytes = text.as_bytes();
                for i in 0..bytes.len().saturating_sub(6) {
                    if bytes[i] == b'"'
                        && (bytes[i + 1] == b'E' || bytes[i + 1] == b'W')
                        && bytes[i + 2..i + 6].iter().all(u8::is_ascii_digit)
                        && bytes[i + 6] == b'"'
                    {
                        out.insert(text[i + 1..i + 6].to_string());
                    }
                }
            }
        }
    }

    #[test]
    fn every_code_is_explained() {
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
        let mut codes = std::collections::BTreeSet::new();
        for dir in ["ras-compiler/src", "ras/src", "ras-form/src"] {
            codes_in(&root.join(dir), &mut codes);
        }
        let missing: Vec<&String> = codes.iter().filter(|c| find(c).is_none()).collect();
        assert!(missing.is_empty(), "no `ras explain` entry for {missing:?}");
        let mut seen = std::collections::BTreeSet::new();
        for e in ENTRIES {
            assert!(seen.insert(e.code), "{} is explained twice", e.code);
        }
    }
}
