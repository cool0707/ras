# Makes edit.xlsm, the workbook the tests of `patch` edit (XlsxWriter):
#   python3 edit.py edit.xlsm ../../../ras-ovba/tests/fixtures/xlsxwriter_vbaProject.bin
import xlsxwriter, sys
wb = xlsxwriter.Workbook(sys.argv[1])
wb.add_vba_project(sys.argv[2])
ws = wb.add_worksheet('Data')
bold = wb.add_format({'bold': True, 'bg_color': '#DDEEFF', 'border': 1})
money = wb.add_format({'num_format': '#,##0'})
ws.write_row('A1', ['品名', '単価', '数量', '金額'], bold)
rows = [('りんご', 120, 3), ('みかん', 80, 10), ('ぶどう', 500, 2), ('もも', 300, 4)]
for i, (n, p, q) in enumerate(rows, start=2):
    ws.write(f'A{i}', n); ws.write(f'B{i}', p, money); ws.write(f'C{i}', q)
    ws.write_formula(f'D{i}', f'=B{i}*C{i}', money, p*q)
ws.write('A6', '合計', bold)
ws.write_formula('D6', '=SUM(D2:D5)', money, 3360)
ws.write_formula('E2', '=MyUdf(D2)', None, 42)
ws.merge_range('A8:C8', '結合セル', bold)
ws.conditional_format('D2:D5', {'type': 'cell', 'criteria': '>', 'value': 500, 'format': bold})
ws.data_validation('C2:C5', {'validate': 'integer', 'criteria': 'between', 'minimum': 1, 'maximum': 100})
ws.autofilter('A1:D5')
ws.write_comment('B3', 'メモです')
ws.insert_button('F2', {'macro': 'say_hello', 'caption': '実行', 'width': 80, 'height': 30})
ws.set_column('A:A', 14); ws.set_column('D:D', 12, money)
ws.set_row(6, 30)
ws.write_url('A10', 'https://example.com', string='リンク')
wb.define_name('Total', '=Data!$D$6')
wb.define_name('Items', '=Data!$A$2:$A$5')
ch = wb.add_chart({'type': 'column'})
ch.add_series({'categories': '=Data!$A$2:$A$5', 'values': '=Data!$D$2:$D$5', 'name': '=Data!$D$1'})
ws.insert_chart('H2', ch)
ws2 = wb.add_worksheet('Summary')
ws2.write_formula('A1', '=Data!D6*2', None, 6720)
ws2.write_formula('A2', '=SUM(Data!D2:D5)', None, 3360)
ws2.write_formula('A3', '=Total+1', None, 3361)
ws2.write('B1', 'x')
ws3 = wb.add_worksheet('Tbl')
ws3.add_table('B2:D5', {'columns': [{'header': 'a'}, {'header': 'b'}, {'header': 'c'}]})
ws3.write_row('B3', [1, 2, 3]); ws3.write_row('B4', [4, 5, 6]); ws3.write_row('B5', [7, 8, 9])
wb.close()
